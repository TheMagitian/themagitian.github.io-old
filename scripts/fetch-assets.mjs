/**
 * One-time asset fetcher.
 *
 * Downloads:
 *  1. Roboto Flex variable font (latin + latin-ext subsets) into src/assets/fonts
 *  2. The Material Symbols (outlined) icons used by the site into
 *     src/assets/icons and regenerates src/data/icon-paths.ts
 *
 * Run with:  node scripts/fetch-assets.mjs
 */
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontDir = join(root, "src/assets/fonts");
const iconDir = join(root, "src/assets/icons");

const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

/** Icons used across the site (Material Symbols outlined). */
const ICONS = [
  "add", "article", "arrow-back", "arrow-forward", "arrow-upward", "bolt",
  "bookmark", "calendar-month", "check", "chevron-left", "chevron-right",
  "close", "code", "content-copy", "contrast", "dark-mode", "edit",
  "expand-more", "filter-list", "gravitational?noop", "home", "keyboard-arrow-up",
  "label", "light-mode", "lightbulb", "link", "mail", "menu", "more-vert",
  "neurology", "open-in-new", "palette", "person", "restart-alt", "rss-feed",
  "schedule", "search", "settings", "share", "star", "swap-horiz", "tune",
  "visibility", "view-list", "language",
].filter((n) => !n.includes("?"));

function cssToSubsets(css, family) {
  const blocks = css.split("/*").slice(1);
  const out = [];
  for (const block of blocks) {
    const name = block.split("*/")[0].trim();
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    if (!url) continue;
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    out.push({ subset: name, url, range, family });
  }
  return out;
}

async function fetchFonts() {
  const url =
    "https://fonts.googleapis.com/css2?family=Roboto+Flex:opsz,wght@9..144,100..900&display=swap";
  const css = await (await fetch(url, { headers: { "User-Agent": UA } })).text();
  const subsets = cssToSubsets(css, "Roboto Flex");
  await mkdir(fontDir, { recursive: true });
  const faces = [];
  for (const subset of subsets) {
    const file = `roboto-flex-${subset.subset}.woff2`;
    const buf = Buffer.from(await (await fetch(subset.url)).arrayBuffer());
    await writeFile(join(fontDir, file), buf);
    faces.push({ ...subset, file, bytes: buf.byteLength });
    console.log(`font: ${file} (${buf.byteLength} bytes)`);
  }
  return faces;
}

async function fetchIcon(name, attempt = 0) {
  const res = await fetch(
    `https://api.iconify.design/material-symbols/${name}.svg?width=24&height=24`,
  );
  if (res.status === 429 && attempt < 6) {
    await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
    return fetchIcon(name, attempt + 1);
  }
  return res;
}

async function fetchIcons() {
  await mkdir(iconDir, { recursive: true });
  const entries = {};
  for (const name of ICONS) {
    const target = join(iconDir, `${name}.svg`);
    let svg;
    if (existsSync(target)) {
      svg = await readFile(target, "utf8");
      console.log(`icon ${name}: cached`);
    } else {
      const res = await fetchIcon(name);
      if (!res.ok) {
        console.warn(`icon ${name}: HTTP ${res.status} (skipped)`);
        continue;
      }
      svg = await res.text();
      await writeFile(target, `${svg.trim()}\n`);
    }
    const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
    if (!inner) continue;
    await writeFile(join(iconDir, `${name}.svg`), `${svg}\n`);
    entries[name] = inner;
  }
  console.log(`icons: ${Object.keys(entries).length} written`);
  const lines = Object.entries(entries)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}:\n    ${JSON.stringify(v)},`)
    .join("\n");
  const file = `/**
 * AUTO-GENERATED by scripts/fetch-assets.mjs - do not edit by hand.
 *
 * Inner SVG markup for the Material Symbols (outlined, 24px) set used by
 * <Icon />. Keys are kebab-case icon names.
 */
export const iconPaths: Record<string, string> = {
${lines}
};

export const iconNames = Object.keys(iconPaths) as IconName[];

export type IconName = keyof typeof iconPaths;
`;
  await writeFile(join(root, "src/data/icon-paths.ts"), file);
  console.log(`wrote src/data/icon-paths.ts (${Object.keys(entries).length} icons)`);
}

await fetchFonts();
await fetchIcons();
